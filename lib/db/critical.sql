  id INTEGER PRIMARY KEY AUTOINCREMENT,
  date DATE NOT NULL,
  turn TEXT NOT NULL,
  dt INT NOT NULL DEFAULT 0,
  semi_count INT NOT NULL DEFAULT 0,
  semi_out INT NOT NULL DEFAULT 0,
  semi_icu INT NOT NULL DEFAULT 0,
  semi_cath INT NOT NULL DEFAULT 0,
  ucp_count INT NOT NULL DEFAULT 0,
  ucp_out INT NOT NULL DEFAULT 0,
  ucp_icu INT NOT NULL DEFAULT 0,
  ucp_cath INT NOT NULL DEFAULT 0,
  eme_count INT NOT NULL DEFAULT 0,
  eme_icu INT NOT NULL DEFAULT 0,
  eme_cath INT NOT NULL DEFAULT 0
);